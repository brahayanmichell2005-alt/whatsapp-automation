// Modelo de acceso a datos para la tabla `products`: el catalogo que la
// IA usa para responder con informacion real (nombres, precios, stock).
// La tabla se crea sola la primera vez; los productos se cargan desde el
// panel de Supabase (o se insertan por SQL). search() busca por palabras
// clave del mensaje del cliente y devuelve los mas relevantes.

const { pool } = require('../config/database');
const logger = require('../utils/logger');

let ready = false;
async function ensureReady() {
  if (ready) return;
  await pool.query(`
    CREATE TABLE IF NOT EXISTS products (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      price TEXT,
      description TEXT,
      stock TEXT,
      active BOOLEAN NOT NULL DEFAULT TRUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  ready = true;
}

function normalize(text) {
  return (text || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

// Palabras "de relleno" que no ayudan a buscar productos.
const STOP_WORDS = new Set([
  'hola', 'buenas', 'buenos', 'dias', 'tardes', 'noches', 'que', 'tal',
  'quiero', 'busco', 'necesito', 'me', 'interesa', 'un', 'una', 'el', 'la',
  'los', 'las', 'de', 'del', 'para', 'por', 'con', 'como', 'cuanto', 'cuesta',
  'precio', 'vale', 'es', 'hay', 'tienen', 'tienes', 'tiene', 'si', 'no',
  'y', 'o', 'a', 'en', 'sobre', 'gracias', 'porfa', 'porfavor', 'favor',
  'dime', 'hola', 'vio', 'ver', 'saber', 'mas', 'informacion', 'info',
  'buen', 'dia', 'disculpa', 'hola', 'donde', 'cuando', 'aqui', 'alli',
]);

// Devuelve hasta `limit` productos activos cuyos datos contengan alguna de
// las palabras clave del texto del cliente (match por ILIKE, sin indices
// fancy: para catalogos de decenas/cientos de productos es suficiente).
async function search(text, limit = 3) {
  await ensureReady();
  const words = normalize(text)
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 3 && !STOP_WORDS.has(w))
    .slice(0, 8);
  if (!words.length) return [];

  const conditions = words
    .map((_, i) => `(name ILIKE $${i + 1} OR description ILIKE $${i + 1})`)
    .join(' OR ');
  const params = words.map((w) => `%${w}%`);
  try {
    const { rows } = await pool.query(
      `SELECT name, price, description, stock FROM products
       WHERE active = TRUE AND (${conditions})
       ORDER BY id ASC LIMIT ${Number(limit) || 3}`,
      params
    );
    return rows;
  } catch (err) {
    logger.error({ err: err.message }, 'Fallo la busqueda de productos para la IA');
    return [];
  }
}

// Lista completa (por si luego se quiere mostrar en el panel).
async function list() {
  await ensureReady();
  const { rows } = await pool.query('SELECT * FROM products ORDER BY id ASC');
  return rows;
}

// ---- CRUD del catalogo desde el panel (pestaña Catálogo) ----
async function getById(id) {
  await ensureReady();
  const { rows } = await pool.query('SELECT * FROM products WHERE id = $1 LIMIT 1', [id]);
  return rows[0] || null;
}

async function create({ name, price = null, description = null, stock = null, active = true }) {
  await ensureReady();
  const { rows } = await pool.query(
    `INSERT INTO products (name, price, description, stock, active)
     VALUES ($1, $2, $3, $4, $5) RETURNING *`,
    [String(name).trim().slice(0, 150), price, description, stock, active === true]
  );
  return rows[0];
}

async function update(id, fields) {
  await ensureReady();
  const allowed = ['name', 'price', 'description', 'stock', 'active'];
  const keys = Object.keys(fields).filter((k) => allowed.includes(k));
  if (!keys.length) return getById(id);
  const setClause = keys.map((k, i) => `${k} = $${i + 1}`).join(', ');
  const values = keys.map((k) => fields[k]);
  const { rows } = await pool.query(
    `UPDATE products SET ${setClause}, updated_at = NOW() WHERE id = $${keys.length + 1} RETURNING *`,
    [...values, id]
  );
  return rows[0] || null;
}

async function remove(id) {
  await ensureReady();
  const { rowCount } = await pool.query('DELETE FROM products WHERE id = $1', [id]);
  return rowCount > 0;
}

module.exports = { ensureReady, search, list, getById, create, update, remove };
